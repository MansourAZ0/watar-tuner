export const strings: Record<Language, Record<StringKey, string>> = { en, ar };

export function t(lang: Language, key: StringKey): string {
  return strings[lang][key] ?? strings.en[key];
}

export function isRtl(lang: Language): boolean {
  return lang === "ar";
}
